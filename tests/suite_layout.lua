local H = dofile("tests/harness.lua")
local Mock = H.Mock
local Library = H.newLibrary()
local Kit = H.load("src/Kit.lua")(Library)
H.load("src/elements/display.lua")(Library, Kit)
H.load("src/elements/input.lua")(Library, Kit)
H.load("src/elements/layout.lua")(Library, Kit)
print("-- Layout elements")

H.test("Accordion: open/close, content height follows children", function()
	local Tab, ctx, page = H.newTab(Library, Kit)
	local states = {}
	local acc = Tab:CreateAccordion({ Name = "Advanced", Description = "More options", Icon = "tune", Callback = function(open) states[#states + 1] = open end })
	local content = acc.Frame:FindFirstChild("Content", true)
	H.eq(acc:IsOpen(), false, "starts closed")
	H.eq(content.Visible, false, "content hidden")
	acc:CreateProgressBar({ Name = "inside", Value = 10 })
	acc:CreateStepper({ Name = "inside2" })
	local inner = acc.Frame:FindFirstChild("Inner", true)
	H.expect(inner:FindFirstChild("inside - ProgressBar") ~= nil, "extension element lands inside the group")
	acc:Open()
	H.eq(acc:IsOpen(), true, "open")
	H.eq(content.Visible, true, "content visible")
	H.expect(content.Size.Y.Offset > 0, "content has height (got " .. content.Size.Y.Offset .. ")")
	Mock.click(acc.Frame:FindFirstChild("Header", true))
	Mock.advance(1)
	H.eq(acc:IsOpen(), false, "header click toggles closed")
	H.eq(content.Visible, false, "hidden after close animation")
	H.eq(states[1], true, "callback open"); H.eq(states[2], false, "callback close")
end)

H.test("Accordion: hosts CORE elements by re-parenting them", function()
	local Tab, ctx, page = H.newTab(Library, Kit)
	local acc = Tab:CreateAccordion({ Name = "Group", Open = true })
	local result = acc:CreateButton({ Name = "CoreBtn" })
	H.expect(result and result.Frame, "core builder result is returned untouched")
	local inner = acc.Frame:FindFirstChild("Inner", true)
	H.expect(inner:FindFirstChild("CoreBtn") ~= nil, "core element moved into the group")
	H.expect(page:FindFirstChild("CoreBtn") == nil, "and is no longer a direct child of the page")
	-- order of mixed elements is preserved
	acc:CreateRating({ Name = "after" })
	local names = {}
	for _, c in ipairs(inner:GetChildren()) do if c:IsA("GuiObject") then names[#names + 1] = c.Name end end
	H.eq(names[1], "CoreBtn", "creation order kept (core first)")
	local ok, err = pcall(function() return acc:CreateToggle({ Name = "x" }) end)
	H.expect(not ok and tostring(err):find("not available"), "missing core method gives a clear error")
end)

H.test("Accordion can nest inside Accordion", function()
	local Tab = H.newTab(Library, Kit)
	local outer = Tab:CreateAccordion({ Name = "Outer", Open = true })
	local inner = outer:CreateAccordion({ Name = "Inner" })
	local leaf = inner:CreateStat({ Name = "Leaf", Value = 1 })
	H.expect(leaf.Frame:IsDescendantOf(outer.Frame), "leaf lives inside nested groups")
	H.eq(inner.Tab, Tab, "context (Tab) is inherited by nested groups")
end)

H.test("SubTabs: pages, selection, hosting", function()
	local Tab, ctx, page = H.newTab(Library, Kit)
	local picked
	local st = Tab:CreateSubTabs({ Tabs = { "General", "Visuals" }, Callback = function(n) picked = n end })
	local general = st:Tab("General")
	local visuals = st:Tab("Visuals")
	general:CreateStepper({ Name = "gen-step" })
	visuals:CreateProgressBar({ Name = "vis-bar" })
	visuals:CreateButton({ Name = "VisCore" })
	H.eq(st:GetSelected(), "General", "first tab selected")
	H.eq(st.Frame:FindFirstChild("Page_General", true).Visible, true, "general page visible")
	H.eq(st.Frame:FindFirstChild("Page_Visuals", true).Visible, false, "other page hidden")
	Mock.click(st.Frame:FindFirstChild("Tab_Visuals", true))
	H.eq(picked, "Visuals", "callback")
	H.eq(st.Frame:FindFirstChild("Page_Visuals", true).Visible, true, "visuals visible")
	H.expect(st.Frame:FindFirstChild("Page_Visuals", true):FindFirstChild("VisCore") ~= nil, "core element inside page")
	st:Select("Nope")
	H.eq(st:GetSelected(), "Visuals", "unknown tab ignored")
	local extra = st:Tab("Extra")
	H.expect(extra ~= nil and st.Pages.Extra, "tabs can be added lazily")
	local n = 0
	for _, c in ipairs(st.Frame:FindFirstChild("Bar", true):GetChildren()) do if c.Name:match("^Tab_") then n = n + 1 end end
	H.eq(n, 3, "buttons rebuilt for 3 tabs")
end)

