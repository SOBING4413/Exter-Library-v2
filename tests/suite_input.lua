H.test("ListPicker: search filter, single + multi select", function()
	local Tab = H.newTab(Library, Kit)
	local sel
	local lp = Tab:CreateListPicker({ Name = "Maps", Options = { "Alpine", "Arctic", "Desert", "Forest" }, Callback = function(v) sel = v end })
	local list = find(lp, "List")
	local function items() local n = 0 for _, c in ipairs(list:GetChildren()) do if c.Name:match("^Item_") then n = n + 1 end end return n end
	H.eq(items(), 4, "all listed")
	find(lp, "Search").Text = "es"
	H.eq(items(), 2, "filtered by substring")
	find(lp, "Search").Text = "zzz"
	H.expect(find(lp, "Empty") ~= nil, "empty state")
	find(lp, "Search").Text = ""
	Mock.click(find(lp, "Item_Desert"))
	H.eq(sel, "Desert", "single select")
	local multi = Tab:CreateListPicker({ Name = "Multi", Options = { "a", "b", "c" }, MultiSelect = true, Callback = function(v) sel = v end })
	Mock.click(find(multi, "Item_a")); Mock.click(find(multi, "Item_c"))
	H.eq(table.concat(sel, ","), "a,c", "multi select")
	Mock.click(find(multi, "Item_a"))
	H.eq(table.concat(multi:GetSelected(), ","), "c", "deselect")
	multi:Refresh({ "c", "d" })
	H.eq(table.concat(multi:GetSelected(), ","), "c", "selection survives refresh")
end)

