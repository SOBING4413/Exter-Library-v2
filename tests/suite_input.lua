local function find(el, name) return el.Frame:FindFirstChild(name, true) end

H.test("Stepper: buttons, typing, snapping, clamping, hold-repeat", function()
	local Tab = H.newTab(Library, Kit)
	local last
	local st = Tab:CreateStepper({ Name = "Count", Range = { 0, 10 }, Increment = 2, CurrentValue = 4, Callback = function(v) last = v end }, "count")
	local box = find(st, "Value")
	H.eq(box.Text, "4", "initial text")
	Mock.click(find(st, "Plus")); Mock.press(find(st, "Plus"), 0, 0); Mock.release(find(st, "Plus"), 0, 0)
	H.eq(st:GetValue(), 6, "plus press adds one step")
	Mock.setText(box, "7")
	H.eq(st:GetValue(), 8, "typed value snaps to increment")
	H.eq(last, 8, "callback fired")
	Mock.setText(box, "99")
	H.eq(st:GetValue(), 10, "clamped to max")
	Mock.setText(box, "abc")
	H.eq(st:GetValue(), 10, "garbage keeps old value")
	Mock.press(find(st, "Minus"), 0, 0); Mock.advance(1.2); Mock.release(find(st, "Minus"), 0, 0)
	H.expect(st:GetValue() < 6, "holding minus repeats (got " .. st:GetValue() .. ")")
	st:Set({ Range = { 0, 1 }, Increment = 0.25, CurrentValue = 0.5, Suffix = "x" })
	H.eq(box.Text, "0.50x", "decimal + suffix display")
	local saved = Library._Parsers.Stepper.Save("count", st)
	H.eq(saved.value, 0.5, "persist save")
	Library._Parsers.Stepper.Load("count", { value = 0.75 })
	H.eq(st:GetValue(), 0.75, "persist load")
end)

H.test("RangeSlider: nearest-handle drag, no crossing, persist", function()
	local Tab = H.newTab(Library, Kit)
	local lo, hi
	local rs = Tab:CreateRangeSlider({ Name = "Rng", Range = { 0, 100 }, CurrentValue = { 25, 75 }, Callback = function(a, b) lo, hi = a, b end }, "rng")
	local track, hit = find(rs, "Track"), find(rs, "Hit")
	track.AbsoluteSize = Vector2.new(200, 6)
	track.AbsolutePosition = Vector2.new(0, 0)
	Mock.press(hit, 50, 0)  -- 25% -> min handle
	Mock.move(120, 0)       -- 60%
	Mock.release(hit, 120, 0)
	H.eq(lo, 60, "min handle dragged"); H.eq(hi, 75, "max untouched")
	Mock.press(hit, 190, 0) -- 95% -> max handle
	Mock.release(hit, 190, 0)
	local a, b = rs:GetValue()
	H.eq(b, 95, "max handle dragged")
	Mock.press(hit, 100, 0) -- 50% closer to min(60)
	Mock.move(400, 0)       -- far right: min cannot pass max
	Mock.release(hit, 400, 0)
	a, b = rs:GetValue()
	H.eq(a, 95, "min clamps at max"); H.eq(b, 95, "max stays")
	H.eq(find(rs, "Value").Text, "95 - 95", "readout")
	rs:Set({ CurrentValue = { 80, 10 } })
	a, b = rs:GetValue(); H.eq(a, 10, "swapped into order"); H.eq(b, 80, "swapped into order")
	local s = Library._Parsers.RangeSlider.Save("rng", rs)
	H.eq(s.value[2], 80, "persist")
	Library._Parsers.RangeSlider.Load("rng", { value = { 5, 6 } })
	a, b = rs:GetValue(); H.eq(a, 5, "load")
end)

