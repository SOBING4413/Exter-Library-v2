local H = dofile("tests/harness.lua")
local Mock = H.Mock
local Library = H.newLibrary()
local Kit = H.load("src/Kit.lua")(Library)
H.load("src/elements/display.lua")(Library, Kit)
print("-- Display elements")

local function text(frame, name) return frame:FindFirstChild(name, true).Text end

H.test("ProgressBar: value, percent, animation target, events", function()
	local Tab = H.newTab(Library, Kit)
	local seen = {}
	local p = Tab:CreateProgressBar({ Name = "Download", Description = "assets", Value = 25, Callback = function(v, a) seen[#seen + 1] = v end }, "dl")
	H.eq(text(p.Frame, "Value"), "25%", "initial percent text")
	H.near(p.Frame:FindFirstChild("Fill", true).Size.X.Scale, 0.25, "fill scale")
	p:SetValue(80)
	H.eq(text(p.Frame, "Value"), "80%", "updated")
	p:Increment(30)
	H.eq(p:GetValue(), 100, "clamped to max")
	H.eq(#seen, 2, "callback only on change")
	p:Set({ Max = 200, Suffix = "XP", Value = 50 })
	H.eq(text(p.Frame, "Value"), "50 / 200 XP", "custom suffix format")
	p:SetIndeterminate(true)
	H.eq(p.Frame:FindFirstChild("Value", true).Visible, false, "value hidden while indeterminate")
	Mock.advance(3)
	p:SetIndeterminate(false)
	H.expect(Library.Options.dl == p, "flag registered")
	H.eq(p.IgnoreConfig, true, "display elements skip config")
	p:SetColor(Color3.fromRGB(255, 0, 0))
	p:Destroy()
end)

H.test("Stat: trend colours, count-up", function()
	local Tab = H.newTab(Library, Kit)
	local st = Tab:CreateStat({ Name = "Revenue", Value = 1200, Prefix = "$", Trend = 4.5, Icon = "bolt" })
	H.eq(text(st.Frame, "Value"), "$1,200", "formatted value")
	local chip = st.Frame:FindFirstChild("Trend", true)
	H.expect(chip.BackgroundColor3 == Kit.Palette.Success, "positive trend is green")
	st:Set({ Trend = -2 })
	H.expect(chip.BackgroundColor3 == Kit.Palette.Error, "negative trend is red")
	local done
	st:OnChanged(function(v) done = v end)
	st:Count(5000, 0.5)
	Mock.advance(1)
	H.eq(done, 5000, "count finished")
	H.eq(text(st.Frame, "Value"), "$5,000", "final text")
	st:Set({ Trend = false })
	H.eq(chip.Visible, false, "trend hidden")
end)

H.test("Callout: types, dismiss", function()
	local Tab = H.newTab(Library, Kit)
	local c = Tab:CreateCallout({ Type = "Warning", Title = "Careful", Content = "This is a long explanation.", Dismissible = true })
	H.eq(text(c.Frame, "Title"), "Careful", "title")
	local fired = false
	c.Dismissed:Connect(function() fired = true end)
	c:Set({ Type = "Error", Content = "Now failing" })
	H.eq(text(c.Frame, "Content"), "Now failing", "content update")
	c:Dismiss(); Mock.advance(1)
	H.expect(fired and c:IsDestroyed(), "dismissed + destroyed")
	local simple = Tab:CreateCallout({ Title = "Plain" })
	H.eq(simple.Frame:FindFirstChild("Content", true).Visible, false, "empty content hidden")
end)

H.test("CodeBlock: highlighting, copy, escaping", function()
	local Tab = H.newTab(Library, Kit)
	local html = Kit.HighlightLua('local x = 5 -- hi <b>\nprint("a&b")')
	H.expect(html:find('<font color="#C792EA">local</font>', 1, true), "keyword colored")
	H.expect(html:find("&lt;b&gt;", 1, true), "rich text escaped")
	H.expect(html:find("&amp;", 1, true), "ampersand escaped")
	H.expect(html:find('color="#F5A97F">5<', 1, true), "number colored")
	H.expect(not html:find("<b>", 1, true), "raw markup never leaks")
	local cb = Tab:CreateCodeBlock({ Name = "Snippet", Code = "print('hi')\nreturn 1" })
	H.eq(cb:GetCode(), "print('hi')\nreturn 1", "code kept")
	H.expect(cb:Copy(), "copy succeeded")
	H.eq(Mock.clipboard, "print('hi')\nreturn 1", "clipboard content")
	cb:Set({ Code = "a\nb\nc" })
	H.eq(cb.Frame:FindFirstChild("Gutter", true).Text, "1\n2\n3", "gutter numbers")
	local safe = Kit.HighlightLua('x = "unterminated\nlocal y')
	H.expect(safe:find("local", 1, true), "unterminated string does not swallow the file")
end)

H.test("DataTable: rows, sorting, selection", function()
	local Tab = H.newTab(Library, Kit)
	local picked
	local t = Tab:CreateDataTable({ Name = "Players", Columns = { "Name", { Name = "Score", Align = "Right" } }, Rows = { { "b", 5 }, { "a", 20 }, { "c", 3 } }, Callback = function(row) picked = row[1] end })
	local rows = t.Frame:FindFirstChild("Rows", true)
	H.eq(#rows:GetChildren() - 1, 3, "3 rows rendered (+ list layout)")
	t:Sort(2, true)
	H.eq(text(rows:GetChildren()[2], "Cell1"), "c", "numeric ascending sort")
	t:Sort(2, false)
	H.eq(text(rows:GetChildren()[2], "Cell1"), "a", "numeric descending sort")
	local header = t.Frame:FindFirstChild("Name", true)
	Mock.click(header)
	H.eq(t.SortColumn, 1, "header click sorts")
	Mock.click(rows:GetChildren()[2])
	H.expect(picked ~= nil, "row callback fired")
	t:AddRow({ "z", 1 }); H.eq(#t:GetRows(), 4, "add row")
	t:Clear(); H.eq(#t:GetRows(), 0, "clear")
end)

H.test("LiveGraph: push, window, autoscale, theme", function()
	local Tab = H.newTab(Library, Kit)
	local g = Tab:CreateLiveGraph({ Name = "FPS", Samples = 10, Suffix = " fps" })
	for i = 1, 25 do g:Push(30 + (i % 7) * 5) end
	H.eq(#g:GetData(), 10, "ring buffer capped at Samples")
	local plot = g.Frame:FindFirstChild("Plot", true)
	local visible = 0
	for _, c in ipairs(plot:GetChildren()) do if c.Name:match("^Seg") and c.Visible then visible = visible + 1 end end
	H.eq(visible, 9, "n-1 visible segments")
	H.expect(text(g.Frame, "Current"):find("fps"), "current value labelled")
	g:Set({ Min = 0, Max = 100 })
	H.eq(text(g.Frame, "Max"), "100 fps", "fixed range label")
	g:Clear()
	H.eq(text(g.Frame, "Current"), "-", "cleared")
	Library:SetTheme({ Color3.fromRGB(9, 9, 9), Color3.fromRGB(9, 9, 9), Color3.fromRGB(9, 9, 9) })
	g:SetData({ 1, 2, 3 })
end)

H.test("KeyValue: set / update / lookup", function()
	local Tab = H.newTab(Library, Kit)
	local kv = Tab:CreateKeyValue({ Items = { { Key = "FPS", Value = 60 }, { "Ping", "40ms" } } })
	H.eq(text(kv.Frame, "Value"), "60", "first value")
	kv:Set("FPS", 144)
	H.eq(kv:GetValue("FPS"), 144, "lookup")
	kv:Set("Region", "EU")
	H.eq(kv:GetValue("Region"), "EU", "appended")
	kv:SetItems({ { "A", 1 } })
	H.eq(kv:GetValue("FPS"), nil, "replaced")
end)

